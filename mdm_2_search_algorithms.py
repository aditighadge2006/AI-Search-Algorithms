def a_star(graph, heuristic, start, goal):
    priority_queue = [(heuristic[start], 0, start, [start])]
    visited = set()

    while priority_queue:
        f, cost, node, path = heapq.heappop(priority_queue)

        if node in visited:
            continue

        visited.add(node)

        if node == goal:
            print("A* Path:", path)
            print("Path Cost:", cost)
            return

        for neighbour, edge_cost in graph[node]:

            if neighbour not in visited:
                new_cost = cost + edge_cost
                new_f = new_cost + heuristic[neighbour]

                heapq.heappush(
                    priority_queue,
                    (new_f, new_cost, neighbour, path + [neighbour])
                )

a_star(weighted_graph, heuristic, 'A', 'G')

# Hill Climbing Algorithm

def hill_climbing():
    current = 0

    values = [1, 3, 5, 7, 6, 4, 2]

    while True:
        left = current - 1
        right = current + 1

        best = current

        if left >= 0 and values[left] > values[best]:
            best = left

        if right < len(values) and values[right] > values[best]:
            best = right

        if best == current:
            break

        current = best

    print("Maximum Value:", values[current])
    print("Position:", current)



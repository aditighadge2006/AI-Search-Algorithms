# Map Coloring using Constraint Satisfaction Problem

# Regions and their neighboring regions
neighbors = {
    'A': ['B', 'C'],
    'B': ['A', 'C', 'D'],
    'C': ['A', 'B', 'D'],
    'D': ['B', 'C']
}

# Available colors
colors = ['Red', 'Green', 'Blue']

# Store the color assigned to each region
assignment = {}


def is_safe(region, color):
    for neighbor in neighbors[region]:
        if neighbor in assignment and assignment[neighbor] == color:
            return False
    return True


def solve(regions):
    if not regions:
        return True

    region = regions[0]

    for color in colors:
        if is_safe(region, color):
            assignment[region] = color

            if solve(regions[1:]):
                return True

            del assignment[region]

    return False


# Solve the CSP
regions = list(neighbors.keys())

if solve(regions):
    print("Map Coloring Solution:")
    for region in regions:
        print(region, "=", assignment[region])
else:
    print("No solution found")